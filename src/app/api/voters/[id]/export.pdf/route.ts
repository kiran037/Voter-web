// app/api/voters/[id]/export.pdf/route.ts
import { NextResponse, type NextRequest } from "next/server";
import { prisma } from "@/lib/prisma";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

// NOTE: On some Next setups, `params` is a Promise.
type RouteParamsPromise = { params: Promise<{ id: string }> };

function toId(s: string) {
  try { return BigInt(s); } catch { return null; }
}

/* ----------------------------- format helpers ----------------------------- */
function fmtDate(d?: Date | string | null) {
  if (!d) return "";
  const dt = typeof d === "string" ? new Date(d) : d;
  if (isNaN(dt.getTime())) return "";
  const dd = String(dt.getDate()).padStart(2, "0");
  const mm = String(dt.getMonth() + 1).padStart(2, "0");
  const yy = dt.getFullYear();
  return `${dd}-${mm}-${yy}`;
}
function ageFromDob(d?: Date | string | null) {
  if (!d) return null;
  const dt = typeof d === "string" ? new Date(d) : d;
  if (isNaN(dt.getTime())) return null;
  const now = new Date();
  let a = now.getFullYear() - dt.getFullYear();
  const m = now.getMonth() - dt.getMonth();
  if (m < 0 || (m === 0 && now.getDate() < dt.getDate())) a--;
  return a;
}
function safe(v: unknown): string {
  if (v == null) return "-";
  const s = String(v).replace(/\s+/g, " ").trim();
  return s.length ? s : "-";
}

/* ---------------------------------- GET ---------------------------------- */
export async function GET(_req: NextRequest, ctx: RouteParamsPromise) {
  try {
    const { id: idStr } = await ctx.params; // <-- await params
    const id = toId(idStr);
    if (!id) return NextResponse.json({ error: "invalid id" }, { status: 400 });

    const v = await prisma.voter.findUnique({
      where: { id },
      include: { head: { select: { id: true, name: true } } },
    });
    if (!v) return NextResponse.json({ error: "not found" }, { status: 404 });

    let family: Array<{ name: string; village: string | null; mobile1: string | null; voterId: string | null }> = [];
    if (v.familyId) {
      family = await prisma.voter.findMany({
        where: { familyId: v.familyId, NOT: { id: v.id } },
        select: { name: true, village: true, mobile1: true, voterId: true },
        orderBy: { id: "asc" },
        take: 1000, // allow large families; we'll paginate in PDF
      });
    }

    const pdfBytes = await buildVoterPdf(v, family);

    const ab = pdfBytes.buffer.slice(pdfBytes.byteOffset, pdfBytes.byteOffset + pdfBytes.byteLength) as ArrayBuffer;
    const blob = new Blob([ab], { type: "application/pdf" });

    return new NextResponse(blob, {
      headers: {
        "Content-Type": "application/pdf",
        "Cache-Control": "no-store",
        "Content-Disposition": `attachment; filename="voter-${v.id}.pdf"`,
      },
    });
  } catch {
    return NextResponse.json({ error: "internal error" }, { status: 500 });
  }
}

/* --------------------------- PDF builder (multi-page) --------------------------- */
async function buildVoterPdf(
  v: any,
  family: Array<{ name: string; village: string | null; mobile1: string | null; voterId: string | null }>
): Promise<Uint8Array> {
  const doc = await PDFDocument.create();

  // A4
  const W = 595.28;
  const H = 841.89;

  // Margins
  const Mx = 28; // horizontal margin
  const My = 30; // vertical margin

  const bw = 0.8; // border width

  const BLACK = rgb(0, 0, 0);
  const GRAY = rgb(0.32, 0.32, 0.32);
  const LIGHT = rgb(0.93, 0.93, 0.93);

  const font = await doc.embedFont(StandardFonts.Helvetica);
  const fontB = await doc.embedFont(StandardFonts.HelveticaBold);

  const tw = (s: string, size = 10, bold = false) =>
    (bold ? fontB : font).widthOfTextAtSize(s ?? "", size);

  const draw = (() => {
    let page = doc.addPage([W, H]);
    let y = H - My;

    const drawFooter = () => {
      const fy = My;
      line(Mx, fy + 12, W - Mx, fy + 12, BLACK, 0.5);
      text("Confidential — For Official Use Only", Mx, fy + 2, 8, false, GRAY);
      const right = "Generated by Voter CMS";
      text(right, W - Mx - tw(right, 8), fy + 2, 8, false, GRAY);
    };

    const newPage = () => {
      drawFooter();
      page = doc.addPage([W, H]);
      y = H - My;
    };

    const text = (s: string, x: number, yTop: number, size = 10, bold = false, color = BLACK) => {
      page.drawText(s ?? "", { x, y: yTop - size - 2, size, font: bold ? fontB : font, color });
    };
    const line = (x1: number, y1: number, x2: number, y2: number, color = BLACK, width = bw) =>
      page.drawLine({ start: { x: x1, y: y1 }, end: { x: x2, y: y2 }, color, thickness: width });
    const cell = (x: number, yTop: number, w: number, h: number, shaded = false) =>
      page.drawRectangle({ x, y: yTop - h, width: w, height: h, borderColor: BLACK, borderWidth: bw, color: shaded ? LIGHT : undefined });

    const ensureSpace = (needed: number) => {
      if (y - needed < My + 40) { // reserve footer space
        newPage();
      }
    };

    const titleBlock = (title: string) => {
      const tSize = 14;
      const metaSize = 9;
      ensureSpace(42);
      const twTitle = tw(title, tSize, true);
      text(title, (W - twTitle) / 2, y, tSize, true);
      y -= 20;
      const meta = `Ref: ${String(v.id)}   •   Date: ${new Date().toLocaleDateString("en-GB")}`;
      text(meta, (W - tw(meta, metaSize)) / 2, y, metaSize, false, GRAY);
      y -= 16;
      line(Mx, y, W - Mx, y, BLACK, 0.6);
      y -= 8;
    };

    const section = (label: string) => {
      const headH = 16;
      const fullW = W - 2 * Mx;
      ensureSpace(headH + 4);
      cell(Mx, y, fullW, headH, true);
      text(label, Mx + 6, y, 10, true);
      y -= headH;
    };

    const kvRow2 = (l1: string, v1: string, l2: string, v2: string) => {
      const rowH = 18;
      const fullW = W - 2 * Mx;
      const half = fullW / 2;

      ensureSpace(rowH);
      cell(Mx, y, half, rowH);
      cell(Mx + half, y, half, rowH);

      // left
      text(truncate(l1, 70, 9, true), Mx + 6, y, 9, true, GRAY);
      text(truncate(v1, half - 80, 10), Mx + 78, y, 10);

      // right
      text(truncate(l2, 70, 9, true), Mx + half + 6, y, 9, true, GRAY);
      text(truncate(v2, half - 80, 10), Mx + half + 78, y, 10);

      y -= rowH;
    };

    const kvRow1 = (label: string, value: string) => {
      const rowH = 18;
      const fullW = W - 2 * Mx;
      ensureSpace(rowH);
      cell(Mx, y, fullW, rowH);
      text(truncate(label, 95, 9, true), Mx + 6, y, 9, true, GRAY);
      text(truncate(value, fullW - 104, 10), Mx + 98, y, 10);
      y -= rowH;
    };

    const tableHeader = () => {
      const th = 16;
      ensureSpace(th);
      cell(Mx, y, tableW, th, true);
      text("#", x0 + 4, y, 8, true);
      text("Name", x1 + 4, y, 8, true);
      text("Village", x2 + 4, y, 8, true);
      text("Mobile", x3 + 4, y, 8, true);
      text("Voter ID", x4 + 4, y, 8, true);
      line(x1, y, x1, y - th);
      line(x2, y, x2, y - th);
      line(x3, y, x3, y - th);
      line(x4, y, x4, y - th);
      y -= th;
    };

    const tableRow = (i: number, m: any) => {
      const trH = 16;
      ensureSpace(trH);
      cell(Mx, y, tableW, trH);
      text(String(i), x0 + 4, y, 9);
      text(truncate(safe(m.name), c1 - 8, 9), x1 + 4, y, 9);
      text(truncate(safe(m.village), c2 - 8, 9), x2 + 4, y, 9);
      text(truncate(safe(m.mobile1), c3 - 8, 9), x3 + 4, y, 9);
      text(truncate(safe(m.voterId), c4 - 8, 9), x4 + 4, y, 9);
      line(x1, y, x1, y - trH);
      line(x2, y, x2, y - trH);
      line(x3, y, x3, y - trH);
      line(x4, y, x4, y - trH);
      y -= trH;
    };

    const truncate = (s: string, maxW: number, size = 10, bold = false) => {
      const str = String(s ?? "");
      if (tw(str, size, bold) <= maxW) return str;
      let out = "";
      for (const ch of str) {
        const test = out + ch + "…";
        if (tw(test, size, bold) <= maxW) out += ch;
        else break;
      }
      return out + "…";
    };

    const tableW = W - 2 * Mx;
    const th = 16;
    const trH = 16;

    const c0 = 22;
    const c1 = 150;
    const c2 = 110;
    const c3 = 110;
    const c4 = tableW - (c0 + c1 + c2 + c3);

    const x0 = Mx;
    const x1 = x0 + c0;
    const x2 = x1 + c1;
    const x3 = x2 + c2;
    const x4 = x3 + c3;

    return {
      yRef: () => y,
      ensureSpace,
      titleBlock,
      section,
      kvRow1,
      kvRow2,
      tableHeader,
      tableRow,
      drawFooter,
      newPage,
    };
  })();

  /* ------------------------------- Header/meta ------------------------------ */
  draw.titleBlock("VOTER INFORMATION RECORD");

  /* ------------------------------- PERSONAL -------------------------------- */
  draw.section("PERSONAL DETAILS");
  const dobStr = fmtDate(v.dob);
  const derivedAge = v.age ?? ageFromDob(v.dob);
  draw.kvRow2("Name", safe(v.name), "Voter ID", safe(v.voterId));
  draw.kvRow2("Father's Name", safe(v.fatherName), "Gender", safe(v.gender));
  draw.kvRow2("DOB", dobStr || "-", "Age", derivedAge != null ? String(derivedAge) : "-");
  draw.kvRow2("Village", safe(v.village), "Ward No", v.wardNo != null ? String(v.wardNo) : "-");
  draw.kvRow1("Address", safe(v.address));

  /* --------------------------------- BOOTH --------------------------------- */
  draw.section("BOOTH & ROLL");
  draw.kvRow2("Booth", safe(v.boothName), "Booth No", v.boothNo != null ? String(v.boothNo) : "-");
  draw.kvRow2("Part No", v.partNo != null ? String(v.partNo) : "-", "SRN", v.srn != null ? String(v.srn) : "-");

  /* --------------------------- CONTACT & STATUS ---------------------------- */
  draw.section("CONTACT & STATUS");
  draw.kvRow2("Mobile 1", safe(v.mobile1), "Mobile 2", safe(v.mobile2));
  draw.kvRow2("Email", safe(v.email), "Colour Code", safe(v.colourCode));
  draw.kvRow2("Voted", v.voted ? "Yes" : "No", "Star Voter", v.starVoter ? "Yes" : "No");
  draw.kvRow1("Status", v.dead ? "Deceased" : "Alive");

  /* ---------------------------- SURVEY / NOTES ----------------------------- */
  draw.section("SURVEY & NOTES");
  draw.kvRow2("Caste", safe(v.caste), "Profession", safe(v.profession));
  draw.kvRow1("Demands", safe(v.demands));
  draw.kvRow1("Notes", safe(v.extraInfo));

  /* -------------------------- PARTY / FAMILY META -------------------------- */
  draw.section("FAMILY & SUPPORT");
  draw.kvRow2("Party Support", safe(v.partySupport), "Family ID Type", safe(v.familyIdType));
  draw.kvRow2("Family ID", safe(v.familyId), "Role", safe(v.relationToHead));
  draw.kvRow1(
    "Family Head",
    v.head?.name ? String(v.head.name) : (v.headId ? String(v.headId) : "-")
  );

  /* ------------------------------ FAMILY TABLE ----------------------------- */
  draw.section("FAMILY MEMBERS");
  draw.tableHeader();

  let index = 1;
  const rowHeight = 16;

  for (const m of family) {
    if (draw.yRef() - rowHeight < 30 + 40) {
      draw.newPage();
      draw.section("FAMILY MEMBERS (cont.)");
      draw.tableHeader();
    }
    draw.tableRow(index++, m);
  }

  draw.drawFooter();
  return await doc.save();
}
